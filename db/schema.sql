CREATE TABLE IF NOT EXISTS MST_ROLES (
  ROLE_ID SERIAL PRIMARY KEY,
  ROLE_NAME VARCHAR(20) NOT NULL UNIQUE
);

INSERT INTO MST_ROLES (ROLE_NAME) VALUES ('Admin'), ('Teacher'), ('Student')
ON CONFLICT (ROLE_NAME) DO NOTHING;

CREATE TABLE IF NOT EXISTS MST_USERS (
  USER_ID SERIAL PRIMARY KEY,
  ROLE_ID INTEGER NOT NULL REFERENCES MST_ROLES (ROLE_ID),
  NAME VARCHAR(150) NOT NULL,
  EMAIL VARCHAR(255) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR(255),
  GOOGLE_ID VARCHAR(255) UNIQUE,
  IS_ACTIVE SMALLINT NOT NULL DEFAULT 1,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  UPDATE_DATE TIMESTAMP,
  DELETE_DATE TIMESTAMP
);

CREATE TABLE IF NOT EXISTS MST_CLASS (
  CLASS_ID SERIAL PRIMARY KEY,
  CODE VARCHAR(30) NOT NULL,
  GROUP_NO VARCHAR(10) NOT NULL DEFAULT '',
  NAME VARCHAR(150) NOT NULL,
  TEACHER_ID INTEGER REFERENCES MST_USERS (USER_ID),
  FACULTY VARCHAR(150) NOT NULL DEFAULT '',
  JOIN_CODE VARCHAR(10) UNIQUE,
  ATTENDANCE_CODE VARCHAR(50) NOT NULL DEFAULT '',
  DAYS VARCHAR(20) NOT NULL DEFAULT '',
  DAY_TEXT VARCHAR(30) NOT NULL DEFAULT '',
  START_MIN INTEGER,
  END_MIN INTEGER,
  ROOM VARCHAR(30) NOT NULL DEFAULT '',
  IS_DEMO SMALLINT NOT NULL DEFAULT 0,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  UPDATE_DATE TIMESTAMP,
  DELETE_DATE TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TBL_ENROLLMENT (
  ENROLLMENT_ID SERIAL PRIMARY KEY,
  STUDENT_ID INTEGER NOT NULL REFERENCES MST_USERS (USER_ID),
  CLASS_ID INTEGER NOT NULL REFERENCES MST_CLASS (CLASS_ID),
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  UNIQUE (STUDENT_ID, CLASS_ID)
);

CREATE TABLE IF NOT EXISTS TBL_ASSIGNMENT (
  ASSIGNMENT_ID SERIAL PRIMARY KEY,
  CLASS_ID INTEGER NOT NULL REFERENCES MST_CLASS (CLASS_ID),
  CREATED_BY INTEGER NOT NULL REFERENCES MST_USERS (USER_ID),
  TITLE VARCHAR(150) NOT NULL,
  INSTRUCTIONS TEXT NOT NULL DEFAULT '',
  ATTACHMENT VARCHAR(255) NOT NULL DEFAULT '',
  DUE_DATE DATE NOT NULL,
  POSTED_DATE DATE NOT NULL DEFAULT CURRENT_DATE,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  UPDATE_DATE TIMESTAMP,
  DELETE_DATE TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TBL_STUDENT_ASSIGNMENT (
  STUDENT_ASSIGNMENT_ID SERIAL PRIMARY KEY,
  STUDENT_ID INTEGER NOT NULL REFERENCES MST_USERS (USER_ID),
  ASSIGNMENT_ID INTEGER NOT NULL REFERENCES TBL_ASSIGNMENT (ASSIGNMENT_ID),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  COMPLETED_AT TIMESTAMP,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  UPDATE_DATE TIMESTAMP,
  UNIQUE (STUDENT_ID, ASSIGNMENT_ID)
);

CREATE TABLE IF NOT EXISTS TBL_NOTIFICATION (
  NOTIFICATION_ID SERIAL PRIMARY KEY,
  USER_ID INTEGER NOT NULL REFERENCES MST_USERS (USER_ID),
  ASSIGNMENT_ID INTEGER REFERENCES TBL_ASSIGNMENT (ASSIGNMENT_ID),
  CLASS_ID INTEGER REFERENCES MST_CLASS (CLASS_ID),
  NOTIF_DATE DATE,
  TITLE VARCHAR(200) NOT NULL,
  MESSAGE TEXT NOT NULL DEFAULT '',
  NOTIF_TYPE VARCHAR(30) NOT NULL,
  IS_READ SMALLINT NOT NULL DEFAULT 0,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS TBL_ATTENDANCE (
  ATTENDANCE_ID SERIAL PRIMARY KEY,
  STUDENT_ID INTEGER NOT NULL REFERENCES MST_USERS (USER_ID),
  CLASS_ID INTEGER NOT NULL REFERENCES MST_CLASS (CLASS_ID),
  ATT_DATE DATE NOT NULL,
  STATUS VARCHAR(20) NOT NULL,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  UNIQUE (STUDENT_ID, CLASS_ID, ATT_DATE)
);

CREATE TABLE IF NOT EXISTS TBL_MATERIAL (
  MATERIAL_ID SERIAL PRIMARY KEY,
  CLASS_ID INTEGER NOT NULL REFERENCES MST_CLASS (CLASS_ID),
  CREATED_BY INTEGER NOT NULL REFERENCES MST_USERS (USER_ID),
  TITLE VARCHAR(150) NOT NULL,
  NOTE TEXT NOT NULL DEFAULT '',
  LINK VARCHAR(500) NOT NULL DEFAULT '',
  FILE_NAME VARCHAR(255) NOT NULL DEFAULT '',
  FILE_TYPE VARCHAR(100) NOT NULL DEFAULT '',
  FILE_DATA BYTEA,
  POSTED_DATE DATE NOT NULL DEFAULT CURRENT_DATE,
  DEL_FLG SMALLINT NOT NULL DEFAULT 0,
  INSERT_DATE TIMESTAMP DEFAULT now(),
  DELETE_DATE TIMESTAMP
);
